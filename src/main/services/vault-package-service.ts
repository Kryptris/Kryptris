/**
 * Portable vault packages deliberately use a format which is unrelated to a
 * profile backup.  The values below are local to this service so a package can
 * neither accidentally be mistaken for a backup nor inherit its access model.
 */
const PACKAGE_MAGIC = Buffer.from('KRYVLT01', 'ascii');
export const VAULT_PACKAGE_FORMAT_VERSION = 1 as const;
export const VAULT_PACKAGE_EXTENSION = '.kryptris-vault';
const CHUNK_SIZE = 1024 * 1024;
const HEADER_LIMIT = 64 * 1024;
const MAX_METADATA_RECORD_BYTES = 32 * 1024 * 1024;
const MAX_ATTACHMENT_BYTES = 100 * 1024 * 1024;
const DEFAULT_MAX_TOTAL_ATTACHMENT_BYTES = 512 * 1024 * 1024;
const RECORD_HEADER_BYTES = 9;
const TAG_BYTES = 16;
const DOCUMENT_RECORD = 0;
const ATTACHMENT_START_RECORD = 1;
const ATTACHMENT_DATA_RECORD = 2;
const ATTACHMENT_END_RECORD = 3;
const MANIFEST_RECORD = 4;
const UUID_V4 = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/iu;
const SHA256 = /^[0-9a-f]{64}$/u;
const ATOMIC_PACKAGE_TEMPORARY =
  /^\..+\.kryptris-vault\.vaulta-tmp-[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/iu;

interface VaultPackageHeader {
  readonly format: 'kryptris-vault-package';
  readonly version: typeof VAULT_PACKAGE_FORMAT_VERSION;
  readonly packageId: string;
  readonly createdAt: string;
  readonly cipher: 'AES-256-GCM-CHUNKED';
  readonly chunkSize: typeof CHUNK_SIZE;
  readonly noncePrefix: string;
  readonly kdf: {
    readonly algorithm: 'argon2id';
    readonly salt: string;
    readonly parameters: Argon2idParameters;
  };
  readonly wrappedPackageKey: AesGcmEnvelope;
}

